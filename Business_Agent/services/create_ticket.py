import sqlite3
from pathlib import Path
from contextlib import closing


# Locate the actual project database.
# This file is inside the services folder, so we move up one folder.
DB_PATH = (
    Path(__file__).resolve().parent.parent
    / "database"
    / "customer.db"
)


def create_ticket(customer_id, issue_title, issue_description):
    """
    Create a support ticket for an existing customer.

    Returns:
        int: The ID of the newly created ticket.

    Raises:
        ValueError: If the customer does not exist.
    """

    # Open the database and guarantee that the connection closes.
    with closing(sqlite3.connect(DB_PATH)) as conn:

        # SELECT checks whether the customer exists.
        cursor = conn.execute(
            """
            SELECT customer_id
            FROM customers
            WHERE customer_id = ?
            """,
            (customer_id,)
        )

        customer = cursor.fetchone()

        # Stop ticket creation if the customer does not exist.
        if customer is None:
            raise ValueError("Customer is not found")

        # Create the ticket only after customer validation.
        cursor = conn.execute(
            """
            INSERT INTO support_tickets
            (customer_id, issue_title, issue_description, status)
            VALUES (?, ?, ?, ?)
            """,
            (
                customer_id,
                issue_title,
                issue_description,
                "Open"
            )
        )

        # Get the ID generated by SQLite.
        ticket_id = cursor.lastrowid

        # Save the ticket permanently.
        conn.commit()

        return ticket_id


def get_ticket(ticket_id):
    """
    Retrieve one ticket using its ID.

    Returns:
        tuple: Ticket details if found, otherwise None.
    """

    with closing(sqlite3.connect(DB_PATH)) as conn:

        cursor = conn.execute(
            """
            SELECT *
            FROM support_tickets
            WHERE ticket_id = ?
            """,
            (ticket_id,)
        )

        ticket = cursor.fetchone()

        return ticket


def update_ticket_status(ticket_id, new_status):
    """
    Update the status of an existing ticket.

    Returns:
        bool: True if a ticket was updated, otherwise False.
    """

    with closing(sqlite3.connect(DB_PATH)) as conn:

        cursor = conn.execute(
            """
            UPDATE support_tickets
            SET status = ?
            WHERE ticket_id = ?
            """,
            (new_status, ticket_id)
        )

        # rowcount tells us whether a ticket was updated.
        ticket_updated = cursor.rowcount > 0

        conn.commit()

        return ticket_updated


def get_customer_tickets(customer_id):
    """
    Retrieve all support tickets belonging to one customer.

    Returns:
        list: All matching tickets.
    """

    with closing(sqlite3.connect(DB_PATH)) as conn:

        cursor = conn.execute(
            """
            SELECT *
            FROM support_tickets
            WHERE customer_id = ?
            ORDER BY ticket_id ASC
            """,
            (customer_id,)
        )

        tickets = cursor.fetchall()

        return tickets